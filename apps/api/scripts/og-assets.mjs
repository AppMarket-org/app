// Regenerates src/og/assets.generated.ts from src/og/assets/*: fonts and logo as base64, so
// they load the same way in the dev server and the deployed Worker.
import { readFileSync, writeFileSync } from "node:fs";

const files = { roboto400: "roboto-400.ttf", roboto700: "roboto-700.ttf", logo: "logo.png" };
const lines = ["// Generated by scripts/og-assets.mjs from src/og/assets. Do not edit.", ""];
for (const [name, file] of Object.entries(files)) {
	lines.push(`export const ${name} = "${readFileSync(new URL(`../src/og/assets/${file}`, import.meta.url)).toString("base64")}";`);
}
writeFileSync(new URL("../src/og/assets.generated.ts", import.meta.url), `${lines.join("\n")}\n`);
